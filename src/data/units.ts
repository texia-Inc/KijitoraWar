// レベルアップのコストと倍率
export const LEVEL_UP_COSTS = [0, 50, 100, 200, 500]; // Lv1→2, 2→3, 3→4, 4→5
export const LEVEL_MULTIPLIERS = [1, 1.1, 1.3, 1.6, 2.1]; // Lv1, 2, 3, 4, 5

export function getUpgradedStats(base: UnitStats, level: number): UnitStats {
  const mult = LEVEL_MULTIPLIERS[level - 1] || LEVEL_MULTIPLIERS[LEVEL_MULTIPLIERS.length - 1];
  return {
    ...base,
    hp: Math.floor(base.hp * mult),
    attack: Math.floor(base.attack * mult),
    level,
  };
}
